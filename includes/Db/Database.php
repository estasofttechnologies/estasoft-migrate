<?php
/**
 * Database access contract used by the engine.
 *
 * @package Estasoft\Migrate
 */

namespace Estasoft\Migrate\Db;

defined( 'ABSPATH' ) || defined( 'ESTASOFT_MIGRATE_TESTING' ) || exit;

/**
 * Everything the engine needs from a database, so the engine can be tested without WordPress.
 */
interface Database {

	/**
	 * Table prefix of this site.
	 *
	 * @return string
	 */
	public function prefix();

	/**
	 * All base tables in the schema.
	 *
	 * @return string[]
	 */
	public function list_tables();

	/**
	 * Does the table exist?
	 *
	 * @param string $table Table name.
	 * @return bool
	 */
	public function table_exists( $table );

	/**
	 * Approximate size details for every table whose name starts with $prefix.
	 *
	 * @param string $prefix Name prefix, empty for all tables.
	 * @return array<string, array{rows:int, data_bytes:int, index_bytes:int, engine:string, collation:string}>
	 */
	public function table_statuses( $prefix = '' );

	/**
	 * Primary key columns in key order, empty when the table has no primary key.
	 *
	 * @param string $table Table name.
	 * @return string[]
	 */
	public function primary_key( $table );

	/**
	 * Column details.
	 *
	 * @param string $table Table name.
	 * @return array<string, array{type:string, binary:bool, numeric:bool}>
	 */
	public function columns( $table );

	/**
	 * CREATE TABLE statement.
	 *
	 * @param string $table Table name.
	 * @return string
	 */
	public function show_create( $table );

	/**
	 * Read the next rows of a table. With key columns the read is a keyset read
	 * (WHERE key > last ORDER BY key LIMIT n), which stays fast on huge tables.
	 *
	 * @param string        $table       Table name.
	 * @param string[]      $key_columns Primary key columns, empty to fall back to LIMIT/OFFSET.
	 * @param string[]|null $after       Key values of the last row already read, null for the first batch.
	 * @param int           $limit       Maximum number of rows.
	 * @param int           $offset      Used only when there are no key columns.
	 * @return array[] Rows as column => string|null.
	 */
	public function fetch_batch( $table, array $key_columns, $after, $limit, $offset = 0 );

	/**
	 * Insert rows (several per statement).
	 *
	 * @param string   $table   Table name.
	 * @param string[] $columns Column names.
	 * @param array[]  $rows    Rows as lists of string|null in column order.
	 * @param string   $mode    replace, ignore or insert.
	 * @return int Rows written.
	 */
	public function insert_rows( $table, array $columns, array $rows, $mode = 'replace' );

	/**
	 * Update one row found by key.
	 *
	 * @param string $table Table name.
	 * @param array  $where Key column => value.
	 * @param array  $set   Column => new value.
	 * @return int Affected rows.
	 */
	public function update_row( $table, array $where, array $set );

	/**
	 * Run a statement that returns no rows.
	 *
	 * @param string $sql SQL.
	 * @return int Affected rows.
	 * @throws DatabaseException On failure.
	 */
	public function query( $sql );

	/**
	 * Run a SELECT. Placeholders are %s and %d, a literal percent sign is %%.
	 *
	 * @param string $sql    SQL.
	 * @param array  $params Values for the placeholders.
	 * @return array[] Rows as column => string|null.
	 * @throws DatabaseException On failure.
	 */
	public function get_results( $sql, array $params = array() );

	/**
	 * First column of the first row, or null.
	 *
	 * @param string $sql    SQL.
	 * @param array  $params Values for the placeholders.
	 * @return string|null
	 */
	public function get_var( $sql, array $params = array() );

	/**
	 * Drop a table if it exists.
	 *
	 * @param string $table Table name.
	 * @return void
	 */
	public function drop_table( $table );

	/**
	 * Rename tables in one atomic step where the server allows it. Renames run in the order given.
	 *
	 * @param array<string,string> $pairs Old name => new name.
	 * @return void
	 */
	public function rename_tables( array $pairs );

	/**
	 * Start a transaction.
	 *
	 * @return void
	 */
	public function begin();

	/**
	 * Commit the transaction.
	 *
	 * @return void
	 */
	public function commit();

	/**
	 * Undo the transaction.
	 *
	 * @return void
	 */
	public function rollback();

	/**
	 * Id generated by the last INSERT.
	 *
	 * @return int
	 */
	public function insert_id();

	/**
	 * Count rows exactly.
	 *
	 * @param string $table Table name.
	 * @return int
	 */
	public function count_rows( $table );

	/**
	 * Largest statement the server accepts, in bytes.
	 *
	 * @return int
	 */
	public function max_allowed_packet();

	/**
	 * Server details: type (mysql, mariadb, sqlite), version, charset, collation.
	 *
	 * @return array{type:string, version:string, charset:string, collation:string}
	 */
	public function server_info();

	/**
	 * Is a collation available on this server?
	 *
	 * @param string $collation Collation name.
	 * @return bool
	 */
	public function has_collation( $collation );

	/**
	 * SQL literal for a value.
	 *
	 * @param mixed $value Value.
	 * @return string
	 */
	public function quote( $value );

	/**
	 * Forget cached column details (after a table was created, dropped or renamed).
	 *
	 * @param string|null $table Table name, null for all.
	 * @return void
	 */
	public function forget( $table = null );
}
